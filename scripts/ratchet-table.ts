// Bakes the ratchet pawl's resting lift (models/ratchetGeometry.ts restingLift) for an unstripped wheel into
// shared/primitives/models/ratchetTable.ts, one row per tooth count. The lift is the same for every tooth, so a row
// covers one tooth pitch: SAMPLES evenly spaced lifts from the previous landing up to `drop`, the share of the pitch
// at which the nose falls into the next notch (and the lift goes back to 0). ratchet.ts interpolates between them.
// Usage: node scripts/ratchet-table.ts   (ratchet.test.ts fails when the file is out of date)
import { writeFileSync } from "node:fs";
import { Wheel, restingLift } from "../shared/primitives/models/ratchetGeometry.ts";
import { ratchet } from "../shared/primitives/models/ratchet.ts";
import { steps } from "../shared/primitives/types.ts";

const SAMPLES = 128;
const FILE = new URL("../shared/primitives/models/ratchetTable.ts", import.meta.url);

/** The share of a pitch at which the pawl drops into the next notch, by bisection. */
function dropAt(lift: (u: number) => number): number {
  let lo = 0.9;
  let hi = 1;
  while (hi - lo > 1e-10) {
    const mid = (lo + hi) / 2;
    if (lift(mid) > 1) lo = mid;
    else hi = mid;
  }
  return hi;
}

const rows = steps(ratchet.sliders[0]!).map((n) => {
  const wheel = new Wheel(n);
  const lift = (u: number) => restingLift(wheel, (3 + u) / n);
  const drop = dropAt(lift);
  const samples = Array.from({ length: SAMPLES + 1 }, (_, i) => lift(i === SAMPLES ? drop - 1e-8 : (drop * i) / SAMPLES));
  return `  ${n}: { drop: ${Number(drop.toFixed(9))}, lift: [${samples.map((x) => Number(x.toFixed(5))).join(", ")}] },`;
});

writeFileSync(
  FILE,
  `// Generated by scripts/ratchet-table.ts. Do not edit.\n/** The pawl's resting lift over one tooth pitch, by tooth count: see the script. */\nexport const REST_LIFT: Record<number, { drop: number; lift: number[] }> = {\n${rows.join("\n")}\n};\n`,
);
console.log(`wrote ${rows.length} rows`);

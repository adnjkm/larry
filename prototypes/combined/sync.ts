// Rebuilds CoursePlus.tsx from Aiden's latest prototypes/lesson/Course.tsx: his file, with the story lesson's additions
// put back in at the same places. Run it after pulling a change of his: `pnpm combined:sync` (this, then oxfmt).
// Each addition is anchored on a line of his; if one of those lines has changed, it stops and names it, and that
// addition is placed by hand.
import { readFileSync, writeFileSync } from "node:fs";

const here = new URL(".", import.meta.url);
let s = readFileSync(new URL("../lesson/Course.tsx", here), "utf8");

/** Replaces `from` with `to`, once; `after` finds it only past that text. */
function put(what: string, from: string, to: string, after?: string) {
  const start = after === undefined ? 0 : s.indexOf(after);
  const at = start < 0 ? -1 : s.indexOf(from, start);
  if (at < 0) throw new Error(`sync: Course.tsx no longer has the line for ${what}:\n${from.split("\n")[0]}`);
  s = s.slice(0, at) + to + s.slice(at + from.length);
}

// Paths: the copy lives one folder over.
s = s.replace(/from "\.\/([A-Za-z.]+)"/g, 'from "../lesson/$1"');
s = s.replace(/import\("\.\/([A-Za-z.]+)"\)/g, 'import("../lesson/$1")');

put(
  "the header",
  "// A mechanism lesson, played:",
  `// The combined lesson's player: GENERATED by sync.ts from Aiden's prototypes/lesson/Course.tsx, with the story lesson's
// features laid over it (pen-plus.ts lists them). Edit Course.tsx or sync.ts, not this file, then run sync.ts.
//
// A mechanism lesson, played:`,
);
put(
  "the imports",
  `import { Actions, Plain, Say, Shell, type Step } from "../lesson/ui.tsx";`,
  `import { Actions, Need, Plain, Say, Shell, type Step, Why } from "../lesson/ui.tsx";
import type { PlusCourse } from "./pen-plus.ts";`,
);
put("the player's name", "export function CourseFlow({", "export function CoursePlusFlow({");
put("the course type", "  course: Course;\n  kit: Kit;", "  course: PlusCourse;\n  kit: Kit;");
put(
  "the primitive screen's Why",
  `        <PrimitiveScreen key={at} primitive={primitive(screen.id)} onBack={back} onDone={next} mechanism={{ name, key: mechanism }} steps={steps} />`,
  `        <WhyOver key={at} id={screen.id} course={course}>
          <PrimitiveScreen primitive={primitive(screen.id)} onBack={back} onDone={next} mechanism={{ name, key: mechanism }} steps={steps} />
        </WhyOver>`,
);
// His player draws no slider screen any more; the combined one draws the story's final, its own copy below.
put(
  "the final's screen",
  "    else body = null;",
  `    else if (screen.kind === "final")
      body = <Final key={at} {...bench} {...page} screen={screen} values={values} onValues={setValues} onNext={onRestart} final={course.final} />;
    else body = null;`,
);

// The page: a requirement line over the question, and a Why key beside it.
put(
  "the page's props",
  "  children,\n}: PageProps & {",
  `  children,
  need,
  why,
}: PageProps & {
  /** The story's requirement line over the question, Met once the screen is done. */
  need?: string;
  /** The story's Why key beside the question. */
  why?: ReactNode;
`,
);
put(
  "the page's requirement line",
  '          <Mechanism name={name} step={step} />\n          <div className="question">',
  '          <Mechanism name={name} step={step} />\n          {need ? <Need text={need} met={done} /> : null}\n          <div className="question">',
);
put("the page's Why key", "<Say kicker={FORMAT[kind]} note={note}>", "<Say kicker={FORMAT[kind]} note={note} why={why}>");

s += `
/**
 * A primitive screen is Aiden's template, drawn whole by PrimitiveScreen; the story's Why key is laid over it, at the
 * right of the row that names the primitive, so his screen needs no change. Its sheet says what the primitive is and
 * what it does in this pen.
 */
function WhyOver({ id, course, children }: { id: string; course: PlusCourse; children: ReactNode }) {
  const box = useRef<HTMLDivElement>(null);
  const [top, setTop] = useState<number>();
  const extra = course.primitiveExtras[id];
  useLayoutEffect(() => {
    const el = box.current;
    if (!el) return;
    const read = () => {
      const row = el.querySelector<HTMLElement>(".notes");
      // In the box's own pixels: the phone may be drawn at a scale.
      const scale = el.getBoundingClientRect().height / el.offsetHeight || 1;
      setTop(row ? (row.getBoundingClientRect().top - el.getBoundingClientRect().top) / scale : undefined);
    };
    read();
    const observer = new ResizeObserver(read);
    observer.observe(el);
    return () => observer.disconnect();
  }, []);
  return (
    <div ref={box} className="why-over">
      {children}
      {extra && top !== undefined ? (
        <div className="why-over-key" style={{ top }}>
          <Why title={primitive(id).name}>
            {extra.why.map((line, i) => (
              <p key={line} className={i === 0 ? "sheet-lead" : undefined}>
                {line}
              </p>
            ))}
            <p>
              <b>In this pen.</b> {extra.use}
            </p>
          </Why>
        </div>
      ) : null}
    </div>
  );
}
`;

s += `
type Tuned = { values: Values; onValues: (next: Values) => void };

/**
 * The story's final: the whole pen with the click in hand, its requirement over it, and every test to pass; then what
 * each part does. Its own copy, since his player no longer draws slider screens; the screen starts with the pen's dials
 * right (pen-plus.ts), so the click is all that is left.
 */
function Final({ story, kit, screen, values, onValues, final, ...page }: Bench & PageProps & Tuned & { screen: Of<"final">; final: PlusCourse["final"] }) {
  const { present } = useParts(story, kit, screen.after);
  const [last, setLast] = useState<Verdict>();
  const [done, setDone] = useState(false);
  return (
    <Page
      kind="final"
      {...page}
      say={screen.say}
      done={done}
      line={done ? screen.success : last?.line}
      bad={!done}
      next="Start Over"
      need={final.need}
      why={
        <Why title={final.title}>
          {final.why.map((line, i) => (
            <p key={line} className={i === 0 ? "sheet-lead" : undefined}>
              {line}
            </p>
          ))}
        </Why>
      }
    >
      <Rig
        story={story}
        kit={kit}
        present={present}
        pink={NONE}
        frame={screen.frame}
        controls={[screen.control]}
        values={values}
        onValues={(v) => {
          setLast(undefined);
          onValues(v);
        }}
        tests={screen.tests}
        onResult={(_, verdict, all) => {
          setLast(verdict);
          if (screen.tests.every((t) => all[t.id]?.pass)) setDone(true);
        }}
      />
      {/* The story's payoff: once the whole pen works, what each part of it does. */}
      {done ? (
        <ul className="payoff" data-payoff>
          {final.payoff.map((p) => (
            <li key={p.part}>
              <b>{p.part}</b> {p.job}
            </li>
          ))}
        </ul>
      ) : null}
    </Page>
  );
}
`;

writeFileSync(new URL("CoursePlus.tsx", here), s);
